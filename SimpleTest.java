public class SimpleTest {
    public static void main(String[] args) {
        // 打印問候語
        System.out.println("Hello, World!");
        
        // 計算 1 到 10 的總和
        int sum = 0;
        for (int i = 1; i <= 10; i++) {
            sum += i;
        }
        
        // 打印總和
        System.out.println("1 到 10 的總和是: " + sum);
    }
}